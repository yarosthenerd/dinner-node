const MB = 1024 * 1024;

/** Largest context that fits alongside the weights, in whole 1024s. */
export function fit(weightsMB, kvPerTokenB, ctx, budgetMB, trainedCtx) {
  const kvMB = (kvPerTokenB * ctx) / MB;
  const needMB = Math.ceil(weightsMB + kvMB + DATA.overheadMB);
  const spare = budgetMB - weightsMB - DATA.overheadMB;
  const raw = spare > 0 ? Math.floor((spare * MB) / kvPerTokenB / 1024) * 1024 : 0;
  return { needMB, fits: needMB <= budgetMB, maxCtx: Math.min(raw, trainedCtx) };
}

/** The last catalog entry that fits whole, or the smallest if none do. */
export function recommendForVram(vramMB, ctx) {
  const budgetMB = Math.floor(vramMB * DATA.vramFraction);
  const scored = DATA.catalog.map(c => ({ c, f: fit(c.weightsMB, c.kvPerTokenB, ctx, budgetMB, c.maxCtx) }));
  const fitting = scored.filter(s => s.f.fits);
  const chosen = fitting.length ? fitting[fitting.length - 1] : scored[0];
  return { pick: chosen.c, fit: chosen.f, fitsWhole: chosen.f.fits, budgetMB };
}

export function estimate(input) {
  const { pick, fit: f, fitsWhole } = recommendForVram(input.vramMB, input.ctx);
  const bw = input.bandwidthMiBs || DATA.referenceBandwidthMiBs;
  const onReference = bw === DATA.referenceBandwidthMiBs;
  const clean = DATA.measured.find(m => m.model === pick.tag && m.onGpuPercent >= 90);
  const spilled = DATA.measured.find(m => m.model === pick.tag && m.onGpuPercent < 90);
  const perToken = pick.activeMB || pick.weightsMB;

  let tokensPerSecond, tokensPerSecondSource;
  if (input.tokensPerSecond > 0) {
    tokensPerSecond = input.tokensPerSecond;
    tokensPerSecondSource = 'given';
  } else if (!fitsWhole) {
    // Before the measured branch: see the note in src/earnings.ts.
    if (spilled) { tokensPerSecond = spilled.tokensPerSecond; tokensPerSecondSource = 'spilled-floor'; }
    else { tokensPerSecond = 0; tokensPerSecondSource = 'unknown'; }
  } else if (clean && onReference) {
    tokensPerSecond = clean.tokensPerSecond;
    tokensPerSecondSource = 'measured';
  } else {
    tokensPerSecond = bw / perToken;
    tokensPerSecondSource = pick.activeMB ? 'scaled-moe' : 'scaled';
  }

  const priced = DATA.prices[pick.tag];
  const usdPerMillion = priced ? priced.usdPerMillion : 0;
  const util = Math.max(0, Math.min(1, input.utilisation));
  const secondsPerMonth = input.hoursPerDay * 3600 * 30 * util;
  const tokensPerMonth = tokensPerSecond * secondsPerMonth;
  const grossUsdPerMonth = (tokensPerMonth / 1e6) * usdPerMillion;
  const grossUsdPerHour = (tokensPerSecond * 3600 / 1e6) * usdPerMillion;
  const gasUsdPerMonth = grossUsdPerMonth * DATA.gasShare;
  const powerUsdPerMonth = (input.watts / 1000) * (secondsPerMonth / 3600) * input.usdPerKwh;

  return {
    pick, fitsWhole, maxCtx: f.maxCtx, needMB: f.needMB,
    tokensPerSecond, tokensPerSecondSource,
    usdPerMillion, band: priced,
    grossUsdPerHour, grossUsdPerMonth, gasUsdPerMonth, powerUsdPerMonth,
    netUsdPerMonth: grossUsdPerMonth - gasUsdPerMonth - powerUsdPerMonth,
    tokensPerMonth,
  };
}

