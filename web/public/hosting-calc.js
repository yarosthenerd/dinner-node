const SOURCE_NOTE = {
  // 'given' was missing here and the page threw the moment an operator entered
  // their own tok/s, which is the path this page actively recommends. Caught by
  // the jsdom render test, not by the arithmetic tests, which is what that test
  // exists for.
  given: ['your measurement', 'Your own number, which beats every estimate on this page. Everything below is computed from it.'],
  measured: ['measured', 'Measured on the reference machine. Not a model of anything.'],
  scaled: ['estimated', 'Extrapolated: decoding one token reads the whole model, so this is bandwidth over weights. Validated to within 10% on the two measured models that fit, never measured for this one.'],
  'scaled-moe': ['estimated, weakest', 'Extrapolated from ACTIVE weights, which are derived rather than measured. This is the least certain number on the page and it drives the largest result.'],
  'spilled-floor': ['floor, model does not fit', 'This model does not fit your VRAM, so ollama will run part of it on the CPU. The figure is what the reference machine measured while spilling, and spill is not predictable: two models spilling on the same card came out 9x apart.'],
  unknown: ['unknown', 'No measurement and no honest way to extrapolate.'],
};

const money = n => (Math.abs(n) < 0.01 && n !== 0 ? `$${n.toFixed(4)}` : `$${n.toFixed(2)}`);
const int = n => Math.round(n).toLocaleString('en-US');

function render() {
  const g = id => document.getElementById(id);
  const num = id => Number(g(id).value);
  const vramMB = num('vram') * 1024;
  const ctx = num('ctx');
  const input = {
    vramMB, ctx,
    hoursPerDay: num('hours'),
    utilisation: num('util') / 100,
    watts: num('watts'),
    usdPerKwh: num('kwh'),
    tokensPerSecond: num('tps'),
    bandwidthMiBs: 0,
  };
  const e = estimate(input);
  // The same estimate with the two demand inputs at their ceiling. Computed by
  // calling estimate again rather than by a second formula, so the headline
  // cannot drift from the table underneath it, and so src/earnings.ts stays the
  // only model of what a node earns.
  const best = estimate({ ...input, hoursPerDay: 24, utilisation: 1 });
  g('utilOut').textContent = `${num('util')}%`;
  g('hoursOut').textContent = `${num('hours')} h`;

  const [label, why] = SOURCE_NOTE[e.tokensPerSecondSource] || ['unlabelled', 'No note for this case, which is itself a bug worth reporting.'];
  const priced = !!e.band;

  g('result').innerHTML = `
    ${priced ? `
    <div class="headline">
      <div class="headline-label">Maximum, on this hardware</div>
      <div class="headline-figure">${money(best.netUsdPerMonth)}<span class="headline-unit"> per month</span></div>
      <div class="headline-note">Serving 24 h a day with a job running the whole time, net of gas and
      electricity. <strong>Your income will differ.</strong> Utilisation is the term that decides it and
      nobody can promise you a number: today this network has two nodes and almost no demand. The table
      below is your own settings, not this ceiling.</div>
    </div>` : ''}
    <table>
      <tr><th>Model you would serve</th><td><code>${e.pick.tag}</code><div class="dim">${e.pick.note}</div></td></tr>
      <tr><th>Fits your VRAM</th><td>${e.fitsWhole
        ? `<span class="ok">yes</span> — needs ${(e.needMB / 1024).toFixed(1)} GB of your ${(vramMB * DATA.vramFraction / 1024).toFixed(1)} GB usable budget`
        : `<span class="bad">NO</span> — needs ${(e.needMB / 1024).toFixed(1)} GB, you have ${(vramMB * DATA.vramFraction / 1024).toFixed(1)} GB usable. Ollama will not refuse; it will run the rest on your CPU and throughput collapses.`}</td></tr>
      <tr><th>Largest context that fits</th><td>${int(e.maxCtx)} tokens</td></tr>
      <tr><th>Throughput</th><td><strong>${e.tokensPerSecond.toFixed(1)} tok/s</strong> <span class="tag ${e.tokensPerSecondSource === 'measured' ? 'tag-ok' : 'tag-warn'}">${label}</span><div class="dim">${why}</div></td></tr>
      <tr><th>Your price</th><td>${priced
        ? `${money(e.usdPerMillion)} per million output tokens<div class="dim">90% of the median of ${e.band.providers} listed provider${e.band.providers === 1 ? '' : 's'} for this model, measured ${e.band.measured}.${e.band.providers < 3 ? ' <strong>Thin band</strong> — this price rests on very few data points.' : ''}</div>`
        : `<span class="bad">no market price exists</span><div class="dim">No provider sells this model as an API, so there is nothing to price against and no income figure can be quoted. Serving it is a hobby, not a business.</div>`}</td></tr>
    </table>

    ${priced ? `
    <table>
      <tr><th>Tokens per month</th><td>${int(e.tokensPerMonth)}</td></tr>
      <tr><th>Gross</th><td>${money(e.grossUsdPerHour)} per serving-hour → <strong>${money(e.grossUsdPerMonth)} per month</strong></td></tr>
      <tr><th>Less gas</th><td>−${money(e.gasUsdPerMonth)} <span class="dim">(settlements are transactions; the node settles once tokens are worth 10x the gas, so gas is 1/10 of gross by construction)</span></td></tr>
      <tr><th>Less electricity</th><td>−${money(e.powerUsdPerMonth)} <span class="dim">(${num('watts')} W while generating, at ${money(num('kwh'))}/kWh — real money, unlike the earnings)</span></td></tr>
      <tr><th>Net</th><td class="${e.netUsdPerMonth > 0 ? 'ok' : 'bad'}"><strong style="font-size:18px">${money(e.netUsdPerMonth)} per month</strong></td></tr>
    </table>` : ''}
  `;
}

if (typeof document !== 'undefined' && document.getElementById('result')) {
  for (const id of ['vram', 'ctx', 'hours', 'util', 'watts', 'kwh', 'tps']) {
    document.getElementById(id).addEventListener('input', render);
    document.getElementById(id).addEventListener('change', render);
  }
  render();
}
